export function translateText(text: string): string {
  const trimmed = text.trim();
  const translated = messages[trimmed];
  if (!translated) return text;
  return text.replace(trimmed, translated);
}

function translateElement(element: Element): void {
  if (element instanceof HTMLElement) {
    for (const attribute of ['title', 'aria-label', 'placeholder', 'alt']) {
      const value = element.getAttribute(attribute);
      if (value) {
        const translated = translateText(value);
        if (translated !== value) element.setAttribute(attribute, translated);
      }
    }
  }
  for (const child of element.childNodes) translateNode(child);
}

function translateNode(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    if (node.parentElement?.closest('script, style, textarea, input, [contenteditable="true"]')) return;
    const original = node.nodeValue;
    if (!original) return;
    const translated = translateText(original);
    if (translated !== original) node.nodeValue = translated;
  } else if (node instanceof Element) {
    translateElement(node);
  }
}

/** Translate React output and later updates, including native tooltip and accessibility text. */
export function startPortugueseUi(): void {
  document.documentElement.lang = 'pt-BR';
  document.title = 'Republica: construa sua cidade';
  translateNode(document.body);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateNode(mutation.target);
      else if (mutation.type === 'attributes') translateNode(mutation.target);
      else for (const node of mutation.addedNodes) translateNode(node);
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['title', 'aria-label', 'placeholder', 'alt'],
  });
}
